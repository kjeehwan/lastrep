const fs = require("node:fs");
const path = require("node:path");
const { Resvg } = require("@resvg/resvg-js");

// Shared code-native artwork: the Home wordmark outline, not the legacy bitmap.
function wordmarkAssets(root) {
  const { path: outline, bounds: b, native } = JSON.parse(fs.readFileSync(path.join(root, "src/branding/wordmarkGeometry.json"), "utf8"));
  const size = native.canvas;
  const scale = native.wordmarkWidth / b.width;
  const x = (size - native.wordmarkWidth) / 2 - b.x * scale;
  const y = (size - b.height * scale) / 2 - b.y * scale;
  const n = (value) => Number(value.toFixed(6));
  const result = {};
  for (const [variant, sourceSet, start, end] of [
    ["dev", "dev", "#ffab3d", "#ff5c3d"], ["prod", "main", "#4a90e2", "#7b61ff"],
  ]) {
    result[`assets/images/wordmark-splash-${variant}.svg`] = `<!-- Generated by scripts/wordmark-assets.js from Home wordmark geometry. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <defs><linearGradient id="brand" gradientUnits="userSpaceOnUse" x1="${n(b.x)}" y1="${n(b.y)}" x2="${n(b.x+b.width)}" y2="${n(b.y+b.height)}"><stop stop-color="${start}"/><stop offset="1" stop-color="${end}"/></linearGradient></defs>
  <path transform="translate(${n(x)} ${n(y)}) scale(${n(scale)})" fill="url(#brand)" d="${outline}"/>
</svg>
`;
    // Expo's splash plugin accepts PNG, while Android uses the vector directly.
    result[`assets/images/wordmark-splash-${variant}.png`] = new Resvg(result[`assets/images/wordmark-splash-${variant}.svg`], {
      fitTo: { mode: "width", value: size * 3 },
    }).render().asPng();
    result[`android/app/src/${sourceSet}/res/drawable/splashscreen_brand.xml`] = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/wordmark-assets.js; 112dp wordmark inside Android's 192dp safe circle. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
  android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${size}" android:viewportHeight="${size}">
  <group android:scaleX="${n(scale)}" android:scaleY="${n(scale)}" android:translateX="${n(x)}" android:translateY="${n(y)}">
    <path android:pathData="${outline}">
      <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="${n(b.x)}" android:startY="${n(b.y)}" android:endX="${n(b.x+b.width)}" android:endY="${n(b.y+b.height)}">
          <item android:offset="0" android:color="${start}"/><item android:offset="1" android:color="${end}"/>
        </gradient>
      </aapt:attr>
    </path>
  </group>
</vector>
`;
  }
  return result;
}
function verifyWordmarkAssets(root) {
  return Object.entries(wordmarkAssets(root)).filter(([file, content]) => !fs.existsSync(path.join(root, file)) ||
    (Buffer.isBuffer(content) ? !fs.readFileSync(path.join(root, file)).equals(content) : fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n") !== content)).map(([file]) => file);
}
if (require.main === module) {
  const root = path.resolve(__dirname, "..");
  for (const [file, content] of Object.entries(wordmarkAssets(root))) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), content);
  }
  console.log("Generated dev/prod splash vectors from the shared Home wordmark.");
}
module.exports = { wordmarkAssets, verifyWordmarkAssets };
